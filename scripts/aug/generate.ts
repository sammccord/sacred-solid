const REGIONS = ["tl", "t", "tr", "r", "br", "b", "bl", "l"] as const;
const FLAGS = ["border", "inlay", "both", "delegated-border", "delegated-inlay"] as const;

type Region = (typeof REGIONS)[number];

function isRegion(value: string): value is Region {
  return (REGIONS as readonly string[]).includes(value);
}

export interface MixinTable {
  regions: Record<Region, string[]>;
  all: string[];
  flags: string[];
}

export function scrapeMixins(css: string): MixinTable {
  const names = new Set(
    [...css.matchAll(/\[data-augmented-ui~="([^"]+)"\]/g)].map((match) => match[1]),
  );
  const table: MixinTable = {
    regions: { tl: [], t: [], tr: [], r: [], br: [], b: [], bl: [], l: [] },
    all: [],
    flags: [],
  };
  for (const name of [...names].sort()) {
    const dash = name.indexOf("-");
    const head = dash === -1 ? name : name.slice(0, dash);
    const tail = name.slice(dash + 1);
    if (isRegion(head)) table.regions[head].push(tail);
    else if (head === "all") table.all.push(tail);
    else if ((FLAGS as readonly string[]).includes(name)) table.flags.push(name);
    else throw new Error(`unrecognized augmented-ui mixin "${name}"`);
  }
  for (const flag of FLAGS) {
    if (!table.flags.includes(flag)) throw new Error(`augmented-ui lost the "${flag}" mixin`);
  }
  return table;
}

function tuple(values: readonly string[]): string {
  return `[${values.map((value) => JSON.stringify(value)).join(", ")}] as const`;
}

export function generate(css: string): string {
  const table = scrapeMixins(css);
  const regionLines = REGIONS.map((region) => `  ${region}: ${tuple(table.regions[region])},`);
  return [
    "// Generated by scripts/gen-aug.ts from node_modules/augmented-ui/augmented-ui.css.",
    "// Do not edit. Rerun `vpx scripts/gen-aug.ts` after upgrading augmented-ui.",
    "",
    `export const AUG_REGIONS = ${tuple(REGIONS)};`,
    "",
    "export const AUG_REGION_MIXINS = {",
    ...regionLines,
    "} as const;",
    "",
    `export const AUG_ALL_MIXINS = ${tuple(table.all)};`,
    "",
    `export const AUG_FLAG_MIXINS = ${tuple(table.flags)};`,
    "",
  ].join("\n");
}
